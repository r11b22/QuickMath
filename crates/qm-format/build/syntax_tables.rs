//! Turns `src/math/syntax.toml` into the Rust tables that
//! `src/math/symbols.rs` includes. See the header of that file for its format.
//!
//! Shared by `build.rs` and `tests/syntax_file.rs`, so it only uses `toml`
//! and the standard library.

use std::cmp::Reverse;
use std::collections::HashSet;

use toml::{Table, Value};

/// Characters the lexer gives a token kind of their own before it looks for
/// operators, so an operator spelling cannot start with one.
const RESERVED_OPERATOR_STARTS: &str = "()[]{}_^'\"`\\";

/// The fraction slash is its own token; it only starts longer operators (`//`).
const SLASH: &str = "/";

const OPERATOR_SECTIONS_ONLY: &str =
    "operator spellings only go in the letter, symbol, relation, binary and punctuation sections";

/// Section names in the file, with the title the help panel shows.
const SECTIONS: [(&str, &str); 16] = [
    ("letter", "Letters"),
    ("symbol", "Symbols"),
    ("relation", "Relations"),
    ("binary", "Binary operators"),
    ("punctuation", "Punctuation"),
    ("large-operator", "Large operators"),
    ("integral", "Integrals"),
    ("function", "Functions"),
    ("structure", "Roots and fractions"),
    ("fence", "Fences"),
    ("accent", "Accents"),
    ("font", "Fonts"),
    ("matrix", "Matrices"),
    ("space", "Spacing"),
    ("postfix", "Postfix powers"),
    ("prose", "Prose words"),
];

/// How the symbols of one section look and space.
struct SymbolKind {
    class: &'static str,
    style: &'static str,
    allows_operators: bool,
}

/// Generates the Rust tables, or describes the first problem in `source`.
pub fn generate(source: &str) -> Result<String, String> {
    let file: Table = source.parse().map_err(|error| format!("{error}"))?;
    let mut tables = Tables::default();
    for (section, entries) in &file {
        let title = section_title(section).ok_or_else(|| unknown_section(section))?;
        let entries = entries
            .as_table()
            .ok_or_else(|| format!("`{section}` must be a [section] of entries"))?;
        tables.vocabulary.push((title, Vec::new()));
        for (spelling, value) in entries {
            tables
                .add(section, spelling, value)
                .map_err(|problem| format!("[{section}] `{spelling}`: {problem}"))?;
        }
    }
    Ok(tables.to_rust())
}

/// Entries as Rust source expressions, in file order.
#[derive(Default)]
struct Tables {
    /// `(word, Keyword expression)`.
    keywords: Vec<(String, String)>,
    /// `(operator spelling, Symbol expression)`.
    operators: Vec<(String, String)>,
    /// `(section title, [(spelling, example input)])` for the help panel.
    vocabulary: Vec<(&'static str, Vec<(String, String)>)>,
    defined: HashSet<String>,
}

impl Tables {
    fn add(&mut self, section: &str, spelling: &str, value: &Value) -> Result<(), String> {
        if !self.defined.insert(spelling.to_string()) {
            return Err("is defined twice".to_string());
        }
        self.add_definition(section, spelling, value)?;
        if let Some((_, entries)) = self.vocabulary.last_mut() {
            entries.push((
                spelling.to_string(),
                example_input(section, spelling, value),
            ));
        }
        Ok(())
    }

    fn add_definition(
        &mut self,
        section: &str,
        spelling: &str,
        value: &Value,
    ) -> Result<(), String> {
        if let Some(kind) = symbol_kind(section) {
            let symbol = symbol_expression(value, kind.class, kind.style)?;
            if is_word(spelling) {
                self.keywords
                    .push((spelling.to_string(), format!("Keyword::Symbol({symbol})")));
                return Ok(());
            }
            check_operator_spelling(spelling)?;
            if !kind.allows_operators {
                return Err(OPERATOR_SECTIONS_ONLY.to_string());
            }
            self.operators.push((spelling.to_string(), symbol));
            return Ok(());
        }
        check_word(spelling)?;
        let keyword = keyword_expression(section, value)?;
        self.keywords.push((spelling.to_string(), keyword));
        Ok(())
    }

    fn to_rust(&self) -> String {
        let mut multi_char: Vec<&str> = self
            .operators
            .iter()
            .map(|(spelling, _)| spelling.as_str())
            .filter(|spelling| spelling.len() > 1)
            .collect();
        // Longest first, so the lexer never stops at a prefix (`<=` of `<=>`).
        multi_char.sort_by_key(|spelling| Reverse(spelling.len()));
        let single_char: String = self
            .operators
            .iter()
            .map(|(spelling, _)| spelling.as_str())
            .filter(|spelling| spelling.len() == 1)
            .collect();
        format!(
            "// Generated by build.rs from src/math/syntax.toml; edit that file instead.\n\n\
             static KEYWORDS: &[(&str, Keyword)] = &[\n{}];\n\n\
             static OPERATORS: &[(&str, Symbol)] = &[\n{}];\n\n\
             pub(crate) const MULTI_CHAR_OPERATORS: [&str; {}] = {:?};\n\n\
             pub(crate) const SINGLE_CHAR_OPERATORS: &str = {:?};\n\n\
             static VOCABULARY: &[VocabularySection] = &[\n{}];\n",
            rust_entries(&self.keywords),
            rust_entries(&self.operators),
            multi_char.len(),
            multi_char,
            single_char,
            self.vocabulary_sections(),
        )
    }

    fn vocabulary_sections(&self) -> String {
        self.vocabulary
            .iter()
            .filter(|(_, entries)| !entries.is_empty())
            .map(|(title, entries)| {
                let entries: String = entries
                    .iter()
                    .map(|(spelling, example)| {
                        format!(
                            "        VocabularyEntry {{ spelling: {spelling:?}, example: {example:?} }},\n"
                        )
                    })
                    .collect();
                format!("    VocabularySection {{\n        title: {title:?},\n        entries: &[\n{entries}        ],\n    }},\n")
            })
            .collect()
    }
}

/// Math input that shows an entry in use, for the help panel.
fn example_input(section: &str, spelling: &str, value: &Value) -> String {
    match (section, value.as_str()) {
        ("structure", Some("root")) => format!("{spelling} 3 x"),
        ("structure", Some("over")) => format!("a {spelling} b"),
        ("structure" | "fence" | "accent" | "font", _) => format!("{spelling} x"),
        ("matrix", _) => format!("{spelling} a b, c d"),
        ("space", _) => format!("a {spelling} b"),
        ("postfix", _) => format!("x {spelling}"),
        _ => spelling.to_string(),
    }
}

fn rust_entries(entries: &[(String, String)]) -> String {
    entries
        .iter()
        .map(|(spelling, expression)| format!("    ({spelling:?}, {expression}),\n"))
        .collect()
}

fn symbol_kind(section: &str) -> Option<SymbolKind> {
    let (class, style, allows_operators) = match section {
        "letter" => ("AtomClass::Ordinary", "AtomStyle::Italic", true),
        "symbol" => ("AtomClass::Ordinary", "AtomStyle::Upright", true),
        "relation" => ("AtomClass::Relation", "AtomStyle::Upright", true),
        "binary" => ("AtomClass::Binary", "AtomStyle::Upright", true),
        "punctuation" => ("AtomClass::Punctuation", "AtomStyle::Upright", true),
        "large-operator" => (
            "AtomClass::LargeOperator { limits: true }",
            "AtomStyle::Upright",
            false,
        ),
        "integral" | "function" => (
            "AtomClass::LargeOperator { limits: false }",
            "AtomStyle::Upright",
            false,
        ),
        _ => return None,
    };
    Some(SymbolKind {
        class,
        style,
        allows_operators,
    })
}

fn keyword_expression(section: &str, value: &Value) -> Result<String, String> {
    let expression = match section {
        "structure" => {
            let structures = [("sqrt", "Sqrt"), ("root", "Root"), ("over", "Over")];
            format!("Keyword::{}", named(value, &structures)?)
        }
        "fence" => {
            let (open, close) = text_pair(value, "[\"open\", \"close\"]")?;
            format!("Keyword::Fence {{ open: {open:?}, close: {close:?} }}")
        }
        "matrix" => {
            let (open, close) = text_pair(value, "[\"open\", \"close\"]")?;
            format!("Keyword::Matrix {{ open: {open:?}, close: {close:?} }}")
        }
        "accent" => {
            let accents = [
                ("hat", "Hat"),
                ("bar", "Bar"),
                ("vector", "Vector"),
                ("dot", "Dot"),
                ("double-dot", "DoubleDot"),
                ("tilde", "Tilde"),
            ];
            format!("Keyword::Accent(AccentKind::{})", named(value, &accents)?)
        }
        "font" => {
            let fonts = [
                ("calligraphic", "Calligraphic"),
                ("bold", "Bold"),
                ("blackboard", "Blackboard"),
            ];
            format!("Keyword::Font(Font::{})", named(value, &fonts)?)
        }
        "space" => space_expression(value)?,
        "postfix" => {
            let symbol = symbol_expression(value, "AtomClass::Ordinary", "AtomStyle::Upright")?;
            format!("Keyword::Postfix({symbol})")
        }
        "prose" => {
            let text = value
                .as_str()
                .filter(|text| !text.is_empty())
                .ok_or("expected the shown text, e.g. \"otherwise\"")?;
            format!("Keyword::Prose({text:?})")
        }
        _ => return Err(unknown_section(section)),
    };
    Ok(expression)
}

fn section_title(section: &str) -> Option<&'static str> {
    SECTIONS
        .iter()
        .find(|(name, _)| *name == section)
        .map(|(_, title)| *title)
}

fn unknown_section(section: &str) -> String {
    let names: Vec<&str> = SECTIONS.iter().map(|(name, _)| *name).collect();
    format!(
        "[{section}] is not a section; expected one of {}",
        names.join(", ")
    )
}

fn symbol_expression(value: &Value, class: &str, style: &str) -> Result<String, String> {
    let (text, latex) = text_pair(value, "[\"Unicode text\", 'LaTeX']")?;
    if text.is_empty() || latex.is_empty() {
        return Err("the text and the LaTeX must not be empty".to_string());
    }
    Ok(format!(
        "Symbol {{ text: {text:?}, latex: {latex:?}, class: {class}, style: {style} }}"
    ))
}

fn space_expression(value: &Value) -> Result<String, String> {
    const EXPECTED: &str = "expected { width = \"quad\", count = 1 }";
    let table = value.as_table().ok_or(EXPECTED)?;
    let widths = [
        ("thin", "Thin"),
        ("medium", "Medium"),
        ("thick", "Thick"),
        ("quad", "Quad"),
    ];
    let width = named(table.get("width").ok_or(EXPECTED)?, &widths)?;
    let count = table
        .get("count")
        .and_then(Value::as_integer)
        .filter(|count| *count >= 1)
        .ok_or("`count` must be a whole number of at least 1")?;
    if table.len() != 2 {
        return Err(EXPECTED.to_string());
    }
    Ok(format!(
        "Keyword::Space {{ width: SpaceWidth::{width}, count: {count} }}"
    ))
}

/// The Rust variant for a value that must be one of `names`' data names.
fn named(value: &Value, names: &[(&str, &'static str)]) -> Result<&'static str, String> {
    let expected = || {
        let options: Vec<String> = names
            .iter()
            .map(|(name, _)| format!("\"{name}\""))
            .collect();
        format!("expected one of {}", options.join(", "))
    };
    let name = value.as_str().ok_or_else(expected)?;
    names
        .iter()
        .find(|(candidate, _)| *candidate == name)
        .map(|(_, variant)| *variant)
        .ok_or_else(expected)
}

fn text_pair<'a>(value: &'a Value, shape: &str) -> Result<(&'a str, &'a str), String> {
    let expected = || format!("expected {shape}");
    match value.as_array().map(Vec::as_slice) {
        Some([first, second]) => match (first.as_str(), second.as_str()) {
            (Some(first), Some(second)) => Ok((first, second)),
            _ => Err(expected()),
        },
        _ => Err(expected()),
    }
}

/// Words are what the lexer reads as one word token: ASCII letters, then
/// optionally digits (`integral2`).
fn is_word(spelling: &str) -> bool {
    let digits = spelling.trim_start_matches(|c: char| c.is_ascii_alphabetic());
    digits.len() < spelling.len() && digits.chars().all(|c| c.is_ascii_digit())
}

fn check_word(spelling: &str) -> Result<(), String> {
    if is_word(spelling) {
        return Ok(());
    }
    Err("this section only takes words: ASCII letters, optionally followed by digits".to_string())
}

fn check_operator_spelling(spelling: &str) -> Result<(), String> {
    let is_printable_ascii = spelling.chars().all(|c| c.is_ascii_graphic());
    let starts_like_operator = spelling
        .starts_with(|c: char| c.is_ascii_punctuation() && !RESERVED_OPERATOR_STARTS.contains(c));
    if !is_printable_ascii || !starts_like_operator {
        return Err(format!(
            "not a valid spelling: a word is ASCII letters optionally followed by digits, \
             and an operator starts with ASCII punctuation other than \
             {RESERVED_OPERATOR_STARTS}"
        ));
    }
    if spelling == SLASH {
        return Err("a lone `/` is the fraction slash".to_string());
    }
    Ok(())
}
